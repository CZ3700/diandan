import { access, readFile } from "node:fs/promises";
import path from "node:path";
import { URL, fileURLToPath } from "node:url";
import {
  loadLocalState,
  localStateDirectory,
} from "./local-experience-state.mjs";
import {
  LOCAL_SERVICE_KEYS,
  localObjectStoragePresignEndpoint,
} from "../apps/api/scripts/local-experience-config.mjs";

const workspaceRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

/**
 * Edge for a publicly exposed TEST instance: Let's Encrypt on each public host, owned loopback
 * TLS upstreams verified against the instance CA. The TEST identity picker, admin and captured
 * mail sit behind Basic Auth; server-to-server calls never pass through this edge.
 */
export function renderLocalExperienceCaddyfile({
  config,
  authUser,
  authHash,
  caPath,
}) {
  if (config.exposure?.mode !== "PUBLIC")
    throw new Error("Only a publicly exposed instance has an edge");
  if (!/^[a-z][a-z0-9_-]{2,31}$/u.test(authUser))
    throw new Error("Invalid Basic Auth user");
  if (!/^\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}$/u.test(authHash))
    throw new Error("Basic Auth needs a bcrypt hash, never a password");
  if (!path.isAbsolute(caPath) || /\s/u.test(caPath))
    throw new Error("Invalid CA path");
  const auth = (matcher = "") =>
    `\tbasic_auth ${matcher}{\n\t\t${authUser} ${authHash}\n\t}\n`;
  const upstream = (port, serverName) =>
    `\treverse_proxy https://127.0.0.1:${port} {\n\t\ttransport http {\n\t\t\ttls_trust_pool file ${caPath}\n\t\t\ttls_server_name ${serverName}\n\t\t}\n\t}\n`;
  const sites = LOCAL_SERVICE_KEYS.map((key) => {
    const host = new URL(config.origins[key]).hostname;
    const guard =
      key === "admin" || key === "mail"
        ? auth()
        : key === "oidc"
          ? `\t@picker path /authorize\n${auth("@picker ")}`
          : "";
    return `${host} {\n${guard}${upstream(config.ports[key], host)}}\n`;
  });
  // Presigned object requests authenticate by signature; the owned proxy also answers localhost.
  const storageHost = new URL(localObjectStoragePresignEndpoint(config))
    .hostname;
  sites.push(`${storageHost} {\n${upstream(config.ports.s3, "localhost")}}\n`);
  return (
    `# Generated by scripts/local-experience-caddy.mjs for instance ${config.instance}; TEST adapters only.\n` +
    sites.join("\n")
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const option = (name) => {
    const at = args.indexOf(name);
    return at < 0 ? undefined : args[at + 1];
  };
  try {
    const instance = option("--instance") ?? "default";
    // Never create an instance here: an edge only fronts one that already exists.
    await access(
      path.join(
        await localStateDirectory(workspaceRoot, instance),
        "config.json",
      ),
    ).catch(() => {
      throw new Error("Unknown local instance; start it first");
    });
    const { config } = await loadLocalState(workspaceRoot, instance);
    const hashFile = option("--auth-hash-file");
    if (!hashFile) throw new Error("--auth-hash-file is required");
    process.stdout.write(
      renderLocalExperienceCaddyfile({
        config,
        authUser: option("--auth-user") ?? "tester",
        authHash: (await readFile(hashFile, "utf8")).trim(),
        caPath: option("--ca-path") ?? "/etc/caddy/fan-support-local-ca.crt",
      }),
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
